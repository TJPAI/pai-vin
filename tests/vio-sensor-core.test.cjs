const assert=require('node:assert/strict');
const V=require('../vio-sensor-core.js');
const b=new V.SensorBuffer(100);
const sample=(t,gz=0)=>({t,gx:0,gy:0,gz,ax:0,ay:0,az:9.81});
for(let t=0;t<=1000;t+=10)assert.equal(b.addImu(sample(t,Math.PI/2)),true);
assert.equal(b.addImu(sample(900)),false);
assert.equal(b.addFrame({t:100,width:640,height:480,features:82}),true);
assert.equal(b.addFrame({t:100,width:640,height:480}),false);
const w=b.between(100,900);assert.equal(w.ok,true,JSON.stringify(w));
const q=V.integrateGyro(w.samples);assert.equal(q.ok,true,JSON.stringify(q));
const expected=Math.PI/2*.8;
assert.ok(Math.abs(q.deltaQuaternion[0]-Math.cos(expected/2))<.001);
assert.ok(Math.abs(q.deltaQuaternion[3]-Math.sin(expected/2))<.001);
assert.equal(q.translationMeters,null);
assert.equal(q.poseWorld,null);
const s=V.fromDeviceMotion({rotationRate:{alpha:90,beta:0,gamma:0},accelerationIncludingGravity:{x:0,y:0,z:9.81}},1100);
assert.ok(s&&Math.abs(s.gz-Math.PI/2)<.00001);
assert.equal(V.fromDeviceMotion({rotationRate:null},100),null);
assert.equal(V.integrateGyro([sample(0),sample(200)]).ok,false);
assert.equal(b.between(1100,1300).ok,false);
assert.equal(b.report().imuSamples,100);
const bracket=new V.SensorBuffer(100);
for(let t=95;t<=325;t+=10)bracket.addImu(sample(t,.3));
const aligned=bracket.between(101,299);
assert.equal(aligned.ok,true,JSON.stringify(aligned));
assert.equal(aligned.samples[0].t,101);
assert.equal(aligned.samples.at(-1).t,299);
assert.equal(aligned.boundaryInterpolation,true);
assert.ok(aligned.maxGapMs<=10);
assert.equal(bracket.between(101,345).reason,'awaiting_imu_bracket');
const missingBefore=new V.SensorBuffer();
for(let t=150;t<=350;t+=10)missingBefore.addImu(sample(t));
assert.equal(missingBefore.between(110,310).reason,'no_imu_before_frame');
const stalled=new V.SensorBuffer();
for(const t of [0,10,20,30,40,190,200,210,220])stalled.addImu(sample(t));
assert.equal(stalled.between(5,215).reason,'imu_internal_gap');
assert.equal(b.addImu(sample(500)),false);
assert.ok(b.report().reordered>=1);

b.reset();assert.equal(b.report().imuSamples,0);
console.log('VIO sensor transport and gyro integration tests PASS');
