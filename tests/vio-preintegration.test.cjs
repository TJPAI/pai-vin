const assert=require('node:assert/strict');
const P=require('../vio-preintegration.js');
const sample=(t,gz=0,ax=0,ay=0,az=9.81)=>({t,gx:0,gy:0,gz,ax,ay,az});
const still=Array.from({length:101},(_,i)=>sample(i*10));
const s=P.integrate(still);
assert.equal(s.ok,true);
assert.ok(Math.abs(s.dt-1)<1e-12);
assert.deepEqual(s.deltaQuaternion,[1,0,0,0]);
assert.ok(Math.abs(s.deltaVelocitySpecificForce[2]-9.81)<1e-9);
assert.ok(Math.abs(s.deltaPositionSpecificForce[2]-4.905)<1e-9);
assert.equal(s.gravityCompensated,false);
assert.equal(s.metricPoseAvailable,false);
assert.equal(s.worldPosition,null);
const rot=P.integrate(Array.from({length:101},(_,i)=>sample(i*10,Math.PI/2,0,0,0)));
assert.ok(Math.abs(rot.deltaQuaternion[0]-Math.SQRT1_2)<1e-7);
assert.ok(Math.abs(rot.deltaQuaternion[3]-Math.SQRT1_2)<1e-7);
const bias=P.integrate(Array.from({length:101},(_,i)=>sample(i*10,.2,0,0,0)),{gyroBias:[0,0,.2]});
assert.ok(Math.abs(bias.deltaQuaternion[3])<1e-8);
const motion=P.integrate([sample(0,0,2,0,0),sample(100,0,2,0,0)]);
assert.ok(Math.abs(motion.deltaVelocitySpecificForce[0]-.2)<1e-9);
assert.ok(Math.abs(motion.deltaPositionSpecificForce[0]-.01)<1e-9);
assert.equal(P.integrate([sample(0),sample(150)]).reason,'invalid_imu_gap');
assert.equal(P.integrate([sample(100),sample(50)]).reason,'invalid_imu_gap');
assert.equal(P.integrate([sample(0)]).reason,'missing_imu');
assert.equal(P.integrate([sample(0),{...sample(10),ax:NaN}]).reason,'invalid_imu');
console.log('IMU preintegration inertial factor tests PASS');
