const assert=require('node:assert/strict'),V=require('../vio-viewport.js');
const portrait=V.rect(720,960,360,480,'contain');
assert.equal(portrait.ok,true);assert.equal(portrait.scaleX,.5);assert.equal(portrait.offsetX,0);
const landscape=V.rect(640,480,256,192,'stretch');
assert.equal(landscape.ok,true);assert.equal(landscape.scaleX,.4);assert.equal(landscape.scaleY,.4);
assert.equal(V.compatibility(portrait,landscape).reason,'source_resolution_mismatch');
const padded=V.rect(640,480,360,480,'contain');
assert.equal(padded.offsetY,105);
const same=V.rect(640,480,256,192,'stretch');
const input={fx:360,fy:360,cx:180,cy:240};
const mapping=V.transform(input,padded,same);
assert.equal(mapping.ok,true);assert.ok(Math.abs(mapping.fx-256)<1e-8);
assert.ok(Math.abs(mapping.fy-256)<1e-8);
assert.ok(Math.abs(mapping.cx-128)<1e-8);
assert.ok(Math.abs(mapping.cy-96)<1e-8);
assert.equal(mapping.verified,false);
assert.equal(V.compatibility(padded,same).reason,'independent_stream_fov_unverified');
assert.equal(V.transform(input,portrait,landscape).reason,'source_frame_size_mismatch');
assert.equal(V.rect(640,480,256,192,'bad').reason,'invalid_fit');
const stretched=V.rect(720,960,256,192,'stretch');
assert.equal(stretched.aspectDistorted,true);
console.log('Camera image canvas transforms and independent-stream FOV gate PASS');