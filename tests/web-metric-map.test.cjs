const assert=require('node:assert/strict');
const {validMap,Track,render}=require('../web-metric-map.js');
const map={schema:'pai-vin-metric-map-v1',units:'m',metricScaleVerified:true,coordinateFrame:'building-floor-xy',floor:1,mapId:'test',landmarks:[{x:0,y:0},{x:2,y:0},{x:0,y:2},{x:2,y:2}]};
assert.equal(validMap(map),true);
assert.equal(validMap({...map,metricScaleVerified:false}),false);
assert.equal(validMap({...map,units:'arbitrary'}),false);
assert.equal(validMap({...map,landmarks:[]}),false);
assert.throws(()=>new Track({...map,metricScaleVerified:false}));
const t=new Track(map);
assert.equal(t.add({x:0,y:0,timestamp:1000,confidence:.9,mapId:'test',floor:1,verified:true}),true);
assert.equal(t.add({x:.4,y:0,timestamp:2000,confidence:.9,mapId:'test',floor:1,verified:true}),true);
assert.equal(t.add({x:100,y:0,timestamp:3000,confidence:.9,mapId:'test',floor:1,verified:true}),false);
assert.equal(t.add({x:.5,y:0,timestamp:2500,confidence:.9,mapId:'test',floor:1,verified:false}),false);
assert.equal(t.poses.length,2);
