const assert=require('node:assert/strict');
const V=require('../vin-vo-path.js');
const s=new V.Sketch();
const staticGray=new Uint8Array(256*192);
for(let i=0;i<staticGray.length;i++)staticGray[i]=(i*43+(i>>8)*7)%170+30;
const same=new Uint8Array(staticGray);
const exposure=Uint8Array.from(staticGray,v=>v+9);
assert.equal(V.frameChange(staticGray,same).ok,false,'identical frame must be stationary');
assert.equal(V.frameChange(staticGray,exposure).ok,false,'global exposure change must be stationary');
const altered=Uint8Array.from(staticGray,(v,i)=>i%5<3?255-v:v);
assert.equal(V.frameChange(staticGray,altered).ok,true,'large structured image change');
const stationaryPoints=Array.from({length:40},(_,i)=>({x:(i%8)*28+15,y:Math.floor(i/8)*30+12,a:i,b:i*3}));
const matches=stationaryPoints.map((p,i)=>({i,j:i}));
const geom={correspond:()=>matches};
let called=0;
const fakePose={estimate(){called++;return {ok:true,inliers:35,ratio:.9,cheirality:30,R:[[1,0,0],[0,1,0],[0,0,1]],t:[1,0,0],matches:40}}};
assert.equal(V.parseStep(stationaryPoints,stationaryPoints,geom,fakePose,{frameChange:V.frameChange(staticGray,same)}).ok,false);
assert.equal(called,0,'static frame must stop before pose solver');
assert.equal(V.parseStep(stationaryPoints,stationaryPoints,geom,fakePose,{frameChange:V.frameChange(staticGray,exposure)}).reason,'stationary_frame');
// A spatially varying parallax field must not be discarded just because
// its flow vectors differ; pure rotation must still fail closed.
const shifted=stationaryPoints.map((v,i)=>({...v,x:v.x+4+(i%4)*2,y:v.y+1+(i%3)*2}));
const realisticPose={estimate(){return {ok:true,inliers:34,ratio:.85,cheirality:27,
 R:[[1,0,0],[0,1,0],[0,0,1]],t:[1,0,0],matches:40}}};
const moving=V.parseStep(stationaryPoints,shifted,geom,realisticPose,{frameChange:{ok:true}});
assert.equal(moving.ok,true,JSON.stringify(moving));
assert.ok(moving.parallaxPx>2.2);
const rotateOnly=stationaryPoints.map(v=>({...v,x:v.x+5,y:v.y+3}));
const rotationRejected=V.parseStep(stationaryPoints,rotateOnly,geom,realisticPose,{frameChange:{ok:true}});
assert.equal(rotationRejected.reason,'pure_rotation_or_no_parallax');
assert.equal(s.append({ok:true,dx:1,dz:0,yaw:0}),true);
assert.equal(s.append({ok:true,dx:0,dz:1,yaw:0}),true);
assert.equal(s.nodes.length,3);
assert.equal(s.nodes[2].x,1);assert.equal(s.nodes[2].y,1);
assert.equal(s.append({ok:false,reason:'weak'}),false);
assert.equal(s.rejected,1);
assert.equal(s.serialize().metric,false);
assert.equal(s.serialize().physicalDistanceKnown,false);
const r=new V.Sketch(s.serialize());assert.deepEqual(r.nodes,s.nodes);
assert.throws(()=>new V.Sketch({...s.serialize(),metric:true}));
assert.equal(V.parseStep([],[],{correspond:()=>[]},{}).ok,false);
let count=0;const ctx={fillRect(){count++},fillText(){},beginPath(){},arc(){},moveTo(){},lineTo(){},stroke(){},fill(){},set fillStyle(v){},set font(v){},set strokeStyle(v){},set lineWidth(v){}};
V.render({width:360,height:300,getContext:()=>ctx},r);
assert.ok(count>0);
console.log('Real relative-VO path contract tests passed');
